package de.sean.blockprot.fabric.mixin;

import de.sean.blockprot.fabric.listeners.BlockEventListener;
import net.minecraft.core.BlockPos;
import net.minecraft.server.level.ServerLevel;
import net.minecraft.util.RandomSource;
import net.minecraft.world.level.block.FallingBlock;
import net.minecraft.world.level.block.state.BlockState;
import org.spongepowered.asm.mixin.Mixin;
import org.spongepowered.asm.mixin.injection.At;
import org.spongepowered.asm.mixin.injection.Inject;
import org.spongepowered.asm.mixin.injection.callback.CallbackInfo;

/**
 * BlockPhysicsEvent/EntityChangeBlockEvent: protected anvils don't fall.
 */
@Mixin(FallingBlock.class)
public abstract class FallingBlockMixin {
    @Inject(method = "tick", at = @At("HEAD"), cancellable = true)
    private void blockprot$protectFalling(BlockState state, ServerLevel level, BlockPos pos, RandomSource random, CallbackInfo ci) {
        if (BlockEventListener.isFallProtected(level, pos, state)) ci.cancel();
    }
}
