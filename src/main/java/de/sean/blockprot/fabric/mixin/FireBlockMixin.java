package de.sean.blockprot.fabric.mixin;

import de.sean.blockprot.fabric.listeners.BlockEventListener;
import net.minecraft.core.BlockPos;
import net.minecraft.util.RandomSource;
import net.minecraft.world.level.Level;
import net.minecraft.world.level.block.FireBlock;
import org.spongepowered.asm.mixin.Mixin;
import org.spongepowered.asm.mixin.injection.At;
import org.spongepowered.asm.mixin.injection.Inject;
import org.spongepowered.asm.mixin.injection.callback.CallbackInfo;

/**
 * BlockBurnEvent: protected blocks don't burn down.
 */
@Mixin(FireBlock.class)
public abstract class FireBlockMixin {
    @Inject(method = "checkBurnOut", at = @At("HEAD"), cancellable = true)
    private void blockprot$protectBlock(Level level, BlockPos pos, int chance, RandomSource random, int age, CallbackInfo ci) {
        if (BlockEventListener.isBurnProtected(level, pos)) ci.cancel();
    }
}
